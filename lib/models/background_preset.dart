/// 설정 화면에서 고르는 배경색.
enum BackgroundPreset {
  // 완전한 검정(기본)
  /// Pure black (default).
  black,

  // 짙은 차콜
  /// Neutral charcoal.
  charcoal,

  // 다크 그레이(팔레트 #574의 #424242)
  /// Dark gray #424242 from palette #574.
  darkGray,

  // 따뜻한 갈색
  /// Warm brown.
  warmBrown,

  // 짙은 남색
  /// Deep navy.
  navy,

  // 흰색(팔레트 #574의 #FFFFFF)
  /// White #FFFFFF from palette #574.
  white,

  // 라이트 그레이(팔레트 #574의 #E0E0E0)
  /// Light gray #E0E0E0 from palette #574.
  lightGray,
}
